def stat_groups():
    """The rune rule set's stat groups (tools/runes/export_runes_json.py EFFECTS_V1, the same lists the game reads from
    runes.json): group -> [field paths], "field@kind|kind" only for those kinds."""
    sys.path.insert(0, str(ROOT / "tools/runes"))
    import export_runes_json as X  # noqa: E402
    return X.EFFECTS_V1["stat_groups"]


ASPECT_GROUPS = {"power": ["power"], "reach": ["reach"], "speed": ["speed", "windup", "duration"], "cost": ["cost"]}
UNGROUPED = []


def in_group(path, kind, group):
    for f in stat_groups().get(group, []):
        name, _, kinds = f.partition("@")
        if name == path and (not kinds or kind in kinds.split("|")):
            return True
    return False


def getp(d, path):
    for k in path.split("."):
        if not isinstance(d, dict) or k not in d:
            return None
        d = d[k]
    return d


def relocate(e, path):
    """Where a draft's field path lives in the emitted ability: normalise() moves some keys into the hit payload
    (status_s, release_shove), its status data (stand_s), its consume (stun_per_stack) or the zone (a pit's life), and
    a channel's payload is its on_hit. A path into a status list names the entry by id (on_hit.statuses.dosed.stacks)."""
    if getp_any(e, path) is not None:
        return path
    moved = {"duration": ["on_hit.status_s"], "on_rise.damage": ["zone.on_enter.damage"]}
    if path == "bonus_damage":
        for part in ("on_hit", "on_arrive"):
            vs = getp_any(e, part + ".bonus_flat_vs")
            if isinstance(vs, dict) and vs:
                moved[path] = ["%s.bonus_flat_vs.%s" % (part, next(iter(vs)))]
    for alt in moved.get(path, []):
        if getp_any(e, alt) is not None:
            return alt
    if path.startswith("payload."):
        return relocate(e, "on_hit." + path[len("payload."):])
    for pre in ("on_hit.", "on_hit.status_data.", "on_hit.consume.", "zone."):
        if getp(e, pre + path) is not None:
            return pre + path
    return path


def getp_any(d, path):
    """getp, but a list of {id, ...} entries is walked by id (the patch op does the same, Player.apply_rune_patch)."""
    for k in path.split("."):
        if isinstance(d, list):
            d = next((x for x in d if isinstance(x, dict) and x.get("id") == k), None)
            continue
        if not isinstance(d, dict) or k not in d:
            return None
        d = d[k]
    return d


def ascension_magnitudes(aid, kind, e):
    """The draft's ascension map (aspect -> field, or 'a + b') must reach a real number of the skill through the
    stat groups (Ascension.aspect_acts). A power field outside the power group becomes a magnitude (counted as power,
    as a self buff's strength is); a reach / speed / cost field outside its groups is listed (UNGROUPED) so its group
    in tools/runes/export_runes_json.py can take it."""
    out = []
    amap = e.get("ascension_fields", {})
    for aspect in list(amap):
        spec = amap[aspect]
        if aspect not in ASPECT_GROUPS:
            continue
        paths = [relocate(e, p.strip()) for p in str(spec).split("+")]
        amap[aspect] = " + ".join(paths)
        for path in paths:
            val = getp_any(e, path)
            numeric = isinstance(val, (int, float)) and not isinstance(val, bool)
            numbers = isinstance(val, list) and val and all(isinstance(x, (int, float)) for x in val)
            if path == "recovery" and aspect == "speed":
                continue                 # every skill has a recovery (its own or the default): the windup group reaches it
            if not numeric and not numbers:
                UNGROUPED.append("%s: %s -> %s (not a number)" % (aid, aspect, path))
                continue
            if any(in_group(path, kind, g) for g in ASPECT_GROUPS[aspect]):
                continue
            if aspect == "power":
                v = float(val[0]) if numbers else float(val)
                as_ = "mult" if path.endswith("_mult") and 0.0 < v < 4.0 else "amount"
                lower = any(w in path for w in ("incoming", "taken", "per_wound")) or (v < 1.0 and as_ == "mult")
                out.append((path, as_, str(amap.get("power_dir", "down" if lower else "up"))))
            else:
                UNGROUPED.append("%s: %s -> %s" % (aid, aspect, path))
    return out


def setp(d, path, value):
    keys = path.split(".")
    for k in keys[:-1]:
        d = d.setdefault(k, OD())
    d[keys[-1]] = value


def clean(x):
    if isinstance(x, float) and x == int(x) and abs(x) < 1e9:
        return float(x)
    return x


