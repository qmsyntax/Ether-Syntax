def category(kind):
    if kind in T.MOVEMENT_KINDS:
        return 2
    if kind in T.CLOSE_KINDS:
        return 1
    return 0


def tree_category(kind):
    """Where a skill hangs in its tree: 0 under the ranged root, 1 under the close one, 2 under the movement one."""
    if kind in ("melee_burst", "targeted_strike", "detonate", "field_pulse", "charge_release"):
        return 1
    if kind in ("dash", "blink", "grapple", "streak", "self_buff", "prop", "summon", "channel"):
        return 2
    return 0


def normalise(aid, aff, s, nums, kind):
    """Move draft keys into the shapes the game reads (hit payload keys, payload-borne durations). Returns kind."""
    on_hit = nums.get("on_hit")
    has_status = isinstance(on_hit, dict) and ("status" in on_hit or "statuses" in on_hit)
    if kind == "self_buff" and "buff" not in nums:
        nums["buff"] = aid
    # a hold that lasts "the skill's duration": the duration rides on the payload as status_s
    if kind in ("smite", "chain", "delayed_blast", "targeted_strike", "melee_burst", "projectile", "beam") and "duration" in nums and has_status:
        on_hit["status_s"] = nums.pop("duration")
        if "duration_per_class" in nums:
            on_hit["status_s_per_class"] = nums.pop("duration_per_class")
    if "stripped_s" in nums and isinstance(nums.get("on_pass"), dict):
        nums["on_pass"]["status_s"] = nums.pop("stripped_s")
    for k in ("status_s_per_heat", "status_s_max", "needs_facing", "release_shove", "dark_status_s", "blind_if_dark",
              "execute_below", "execute_excludes", "unliving_mult", "quells_censer"):
        if k in nums and isinstance(on_hit, dict):
            on_hit[k] = nums.pop(k)
    if "status_s" in nums and isinstance(on_hit, dict):
        on_hit["status_s"] = nums.pop("status_s")
    if isinstance(on_hit, dict) and "elite_stun_mult" in nums:
        on_hit["elite_stun_mult"] = nums.pop("elite_stun_mult")
    for k in ("nudge_per_s", "poise_per_s", "retch_every", "retch_s", "stand_s"):
        if k in nums and isinstance(on_hit, dict):
            on_hit.setdefault("status_data", OD())[k] = nums.pop(k)
    if nums.pop("from_above", False) and isinstance(on_hit, dict):
        on_hit["through"] = True
    if "clean_duration_frac" in nums:
        on_hit["status_s_if_not"] = OD([("status", "bleeding"), ("frac", nums.pop("clean_duration_frac"))])
    if aid == "seepage":
        on_hit["through"] = True
    if "stun_per_stack" in nums or (kind in ("beam", "projectile", "melee_burst", "smite") and "consume_status" in nums):
        c = OD([("status", nums.pop("consume_status"))])
        for src, dst in (("per_stack_damage", "per_stack_damage"), ("per_stack_poise", "per_stack_poise"),
                         ("stun_per_stack", "stun_per_stack"), ("stun_max", "stun_max")):
            if src in nums:
                c[dst] = nums.pop(src)
        if "frozen_counts_as" in nums:
            c["counts"] = OD([("frozen", nums.pop("frozen_counts_as"))])
        if "vent_per_stack" in nums:
            c["vent_per_stack"] = nums.pop("vent_per_stack")
        nums.setdefault("on_hit", OD())["consume"] = c
    if "waterlogged_stacks" in nums:
        nums["consume_counts"] = OD([("waterlogged", nums.pop("waterlogged_stacks"))])
    if aid == "rousing_blow":
        on_hit["bonus_vs"] = OD([(nums.pop("bonus_vs_status"), nums.pop("bonus_mult"))])
        on_hit["poise_vs"] = OD([("asleep", on_hit.pop("poise_vs_asleep"))])
    # a flat bonus against a status (Fracture on the Frozen and Brittle, Downdraft on the Aloft): it rides on the hit
    # that lands - a movement skill's arrival, else on_hit
    if "bonus_vs_status" in nums and "bonus_damage" in nums:
        part = "on_arrive" if kind in ("dash", "blink", "grapple") and isinstance(nums.get("on_arrive"), dict) else "on_hit"
        bonus = nums.pop("bonus_damage")
        vs = OD([(nums.pop("bonus_vs_status"), bonus)])
        if "bonus_also_vs" in nums:
            vs[nums.pop("bonus_also_vs")] = bonus
        nums.setdefault(part, OD())["bonus_flat_vs"] = vs
    if "shard_radius" in nums and isinstance(nums.get("on_hit"), dict):
        nums["on_hit"]["shatter_radius"] = nums.pop("shard_radius")
    if kind == "targeted_strike" and "burst" in nums and "consume_status" not in nums:
        nums["burst_always"] = True
    if aid == "sinkhole":
        # nearest existing behaviour: a zone at the point (simplified, see NOTES)
        kind = "ground_zone"
        rise = nums.pop("on_rise")
        poise = nums.pop("on_hit").get("poise", 0.0)
        for k in ("shape", "rise_time", "climb_out_s"):
            nums.pop(k, None)
        nums["zone"] = OD([("shape", "circle"), ("radius", nums.pop("radius")), ("life", nums.pop("life")), ("tick_s", 0.5),
                           ("payload", OD([("status", rise.get("status", "mired"))])),
                           ("on_enter", OD([("damage", rise.get("damage", 30.0)), ("poise", poise)]))])
    if aid == "sapping_tether":
        nums["shape"] = "tether"
    if "spend_blood" in nums and kind == "melee_burst":
        nums["consume"] = "held_blood"
    if "consume" in nums and nums["consume"] is False:
        del nums["consume"]
        nums["keep_stacks"] = True
    if aid == "night_spill":
        nums["consume"] = "swallowed"
    if "dose_clock" in nums:
        nums["status_lasts"] = OD([("dosed", nums.pop("dose_clock"))])      # read generically: a buff that sets a status's clock
    if "times_flesh" in nums:
        nums.pop("times_flesh")       # every Disease hit is times flesh (the affinity's rule)
    if "inside" in nums:
        nums.pop("inside")            # every Life hit is inside (the affinity's rule)
    return kind


def unread_keys(kind, nums):
    allowed = GENERIC | BY_KIND.get(kind, set())
    out = []
    for k, v in nums.items():
        if k not in allowed and k != "keep_stacks" and k != "consume_counts":
            out.append(k)
        if k in ("on_hit", "on_pass", "on_arrive", "on_stop", "on_rise", "burst", "first_hit", "relay_hit", "payload", "on_break",
                 "on_infected_hit", "corpse_burst") and isinstance(v, dict):
            for pk in v:
                if pk not in PAYLOAD_KEYS | {"burst_radius", "radius", "stacks"}:
                    out.append("%s.%s" % (k, pk))
        if k in ("zone", "leave_zone", "burst_zone", "trail") and isinstance(v, dict):
            for zk in v:
                if zk not in ZONE_KEYS:
                    out.append("%s.%s" % (k, zk))
    return out


def ability_entry(aid, name, aff, d, s, legacy):
    nums = copy.deepcopy(s["numbers"])
    for path, val in T.GAP_FILLS.get(aid, {}).items():
        if val == "payload":
            nums["on_hit"] = nums.pop("payload")
        elif isinstance(val, dict) and path in nums and isinstance(nums[path], dict):
            nums[path].update(val)
        else:
            setp(nums, path, val)
    kind = T.KIND_MAP.get(s["kind"], s["kind"])
    if "reflux_per_cost" not in nums:
        nums["reflux_per_cost"] = T.REFLUX_TIER[d["reflux_tier"]]
    kind = normalise(aid, aff, s, nums, kind)
    moves_with_payload = kind == "dash" and any(isinstance(nums.get(k), dict) for k in ("on_pass", "on_stop", "on_arrive"))
    if kind not in ("self_buff", "rod", "prop", "summon", "field_pulse", "displace", "detonate", "streak", "grapple", "blink") and "on_hit" not in nums and not moves_with_payload:
        nums["on_hit"] = OD()
    missing = []
    if aid in NOTES and NOTES[aid]:
        missing.append(NOTES[aid])      # a hand-written note says it better than the keys it covers
    for k in unread_keys(kind, nums):
        if not (missing and k in KEY_WORDS):
            missing.append(KEY_WORDS.get(k, "'%s' is not built" % k))
    seen = []
    for m in missing:
        if m not in seen:
            seen.append(m)
    e = OD()
    e["name"] = name
    e["affinity"] = aff
    e["kind"] = kind
    if s["kind"] != kind:
        e["draft_kind"] = s["kind"]
    e["targeting"] = s["targeting"]
    e["base_rune"] = s["base_rune"]
    e["rune"] = s["rune"]
    e["signature"] = s["signature"]
    # the aspect -> field map the ascension boost acts on (Brent 2026-10-24; kept as the draft wrote it)
    if s.get("ascension"):
        e["ascension_fields"] = OD((k, v) for k, v in s["ascension"].items())
    # what a skill does for its affinity's role (role | utility) and, for a hybrid, which parent it carries
    fit = s.get("role_fit", s.get("serves"))
    if fit:
        e["role_fit"] = fit
    if s.get("parent_trait"):
        e["parent_trait"] = s["parent_trait"]
    if s.get("starter"):
        e["starter"] = True
    for k, v in nums.items():
        e[k] = v
    mags = list(T.MAGNITUDE.get(aid, [])) + ascension_magnitudes(aid, kind, e)
    if mags:
        seen_m = []
        for m in mags:
            if m[0] not in [x[0] for x in seen_m]:
                seen_m.append(m)
        e["magnitude"] = [OD([("path", p), ("as", a), ("dir", dr)]) for p, a, dr in seen_m]
    old = legacy.get(aid, {}) if aid in T.LEGACY_IDS else {}
    e["verse"] = old.get("verse", "")
    # a new skill's icon: its kind's glyph, marked with its rune (UiDraw.icon draws "glyph:RUNE-ID")
    e["icon"] = old.get("icon", "%s:%s" % (T.ICON_BY_KIND.get(kind, "mote"), s["base_rune"]))
    summary = s["summary"].strip()
    if seen:
        e["simplified"] = "; ".join(seen)
        summary = summary + " (simplified)"
    e["summary"] = summary
    e["good_modifiers"] = [g["rune"] for g in s.get("good_modifiers", [])]
    return e


def build_tree(aff, skills, kit, existing):
    """Tier 1 = the kit. Existing nodes keep their tier and requirements. New ones: cheaper skills first, each hung off
    the root of its own category (ranged, close, movement/self), at most 5 a tier; tier 3 and 4 need either of two from
    the tier above."""
    tree = OD()
    for i, sid in enumerate(kit):
        tree[sid] = OD([("tier", 1), ("col", float(i))])
    for sid, node in existing.items():
        if sid not in tree:
            tree[sid] = OD([("tier", node["tier"]), ("col", float(node.get("col", 0))), ("requires", list(node.get("requires", [])))])
    kind_of = {s["id"]: T.KIND_MAP.get(s["kind"], s["kind"]) for s in skills}
    cat_of = {sid: tree_category(k) for sid, k in kind_of.items()}
    for i, sid in enumerate(kit):
        cat_of[sid] = i
    rest = [s for s in skills if s["id"] not in tree]
    rest.sort(key=lambda s: (s["numbers"].get("cost", s["numbers"].get("cost_per_s", 10)), s["id"]))
    per_tier = min(5, max(3, (len(skills) - 3 + 1) // 2))
    for s in rest:
        cat = cat_of[s["id"]]
        tier = 2
        while sum(1 for n in tree.values() if n["tier"] == tier) >= per_tier:
            tier += 1
        if tier == 2:
            req = [kit[cat]]
        else:
            above = [sid for sid, n in tree.items() if n["tier"] == tier - 1]
            # two of the tier above: those of its own kind first, then those of the next kind round
            above.sort(key=lambda sid: ((cat_of.get(sid, 0) - cat) % 3, sid))
            req = above[:2]
        tree[s["id"]] = OD([("tier", tier), ("col", 0.0), ("requires", req)])
    # spread each tier evenly across the widest tier, ordered by where its prerequisites stand
    width = max(3, max(sum(1 for n in tree.values() if n["tier"] == t) for t in range(1, 6)))
    for tier in range(1, 6):
        ids = [sid for sid, n in tree.items() if n["tier"] == tier]
        if not ids:
            continue
        if tier > 1:
            ids.sort(key=lambda sid: sum(tree[r]["col"] for r in tree[sid].get("requires", []) if r in tree) / max(1, len(tree[sid].get("requires", []))))
        for i, sid in enumerate(ids):
            tree[sid]["col"] = round((i + 0.5) * width / len(ids) - 0.5, 3)
    return tree


