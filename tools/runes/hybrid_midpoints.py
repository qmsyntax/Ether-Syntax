"""The midpoint test (Brent 2026-10-24): do the hybrid affinities fall out between two base affinities?

Eight base affinities, each a mean of three anchor words (the same anchors as forced_affinities.py, plus
Holy and Unholy). For every pair of bases, the normalised midpoint of their two vectors is compared with:

  1. each hybrid candidate: which pair's midpoint is it closest to, and does the midpoint beat both
     parents alone ("lift" = cos(hybrid, midpoint) - max(cos(hybrid, parent)))? A positive lift means the
     pair explains the hybrid better than either parent does;
  2. the open vocabulary: the words most related to BOTH parents (score = the lower of the two cosines),
     i.e. what the data itself puts between them, whatever we would have called it.

GloVe 6B 300d (top 60k words) restricted to WordNet lemmas with tagged usage. Writes
design/runes-data/hybrid-midpoints.md. The anchors are the only hand-chosen input.
"""
import itertools
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(__file__))
import wn_glove as W  # noqa: E402

BASES = {
    'Water': ['water', 'flood', 'wave'], 'Fire': ['fire', 'flame', 'burn'], 'Earth': ['soil', 'stone', 'rock'],
    'Wind': ['wind', 'gust', 'breeze'], 'Light': ['light', 'shine', 'bright'],
    'Dark': ['darkness', 'shadow', 'dark'], 'Life': ['life', 'heal', 'vitality'],
    'Death': ['death', 'die', 'corpse'],
}
HYBRIDS = {
    'Lightning': ['lightning', 'electricity', 'thunder'], 'Ice': ['ice', 'frost', 'snow'],
    'Metal': ['metal', 'iron', 'steel'], 'Blood': ['blood', 'bleed', 'vein'],
    'Nature': ['plant', 'grow', 'vegetation'], 'Dream': ['dream', 'sleep', 'illusion'],
    'Poison': ['poison', 'venom', 'toxic'], 'Disease': ['disease', 'infection', 'plague'],
    'Holy': ['holy', 'sacred', 'divine'], 'Unholy': ['unholy', 'cursed', 'profane'],
}
OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'design', 'runes-data', 'hybrid-midpoints.md')


def unit(v):
    return v / np.linalg.norm(v)


def main():
    vi, X, _rank = W.glove(60000)
    cnt = W.counts()
    vec = lambda ws: unit(X[[vi[w] for w in ws]].mean(0))
    base = {a: vec(ws) for a, ws in BASES.items()}
    hyb = {h: vec(ws) for h, ws in HYBRIDS.items()}
    pairs = list(itertools.combinations(BASES, 2))
    mid = {p: unit(base[p[0]] + base[p[1]]) for p in pairs}

    anchors = {w for ws in list(BASES.values()) + list(HYBRIDS.values()) for w in ws}
    vocab = [w for w in vi if w.isalpha() and len(w) > 2 and w in cnt and sum(cnt[w].values()) >= 3 and w not in anchors]
    V = X[[vi[w] for w in vocab]]
    to_base = {a: V @ base[a] for a in BASES}

    lines = ['# The midpoint test: do hybrids fall between two bases?', '',
             'Generated by `tools/runes/hybrid_midpoints.py` (2026-10-24). GloVe 6B 300d, top 60k words, WordNet lemmas '
             'with tagged usage. Anchors are the only hand-chosen input. **Lift** = cos(hybrid, pair midpoint) minus '
             'its cos to the nearer parent alone: above 0 means the pair explains the hybrid better than either parent.', '',
             '## 1. Each hybrid: its best pairs', '',
             '| Hybrid | Best pair | cos | lift | 2nd | 3rd | nearest single base |', '|---|---|---|---|---|---|---|']
    best = {}
    for h, hv in hyb.items():
        scored = []
        for p in pairs:
            c = float(hv @ mid[p])
            lift = c - max(float(hv @ base[p[0]]), float(hv @ base[p[1]]))
            scored.append((c, lift, p))
        scored.sort(reverse=True)
        single = max(BASES, key=lambda a: float(hv @ base[a]))
        best[h] = scored[0]
        fmt = lambda s: '%s+%s (%.2f, %+.2f)' % (s[2][0], s[2][1], s[0], s[1])
        lines.append('| %s | **%s + %s** | %.2f | %+.2f | %s | %s | %s (%.2f) |' % (
            h, scored[0][2][0], scored[0][2][1], scored[0][0], scored[0][1], fmt(scored[1]), fmt(scored[2]),
            single, float(hv @ base[single])))

    lines += ['', '## 2. Each pair: what lies between them (open vocabulary)', '',
              'Words scored by the LOWER of their two cosines to the parents (related to both, not just one), top 12. '
              'Hybrid candidates that land nearest this pair are named.', '',
              '| Pair | Hybrids landing here | Between both (top 12) |', '|---|---|---|']
    for p in pairs:
        both = np.minimum(to_base[p[0]], to_base[p[1]])
        top = [vocab[i] for i in np.argsort(-both)[:12]]
        here = [h for h, s in best.items() if s[2] == p]
        lines.append('| %s + %s | %s | %s |' % (p[0], p[1], ', '.join(here) or '-', ', '.join(top)))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
